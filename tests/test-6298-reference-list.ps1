<#
  test-6298-reference-list.ps1

  The reference load order a release packs (profile\plugins.txt and
  loadorder.txt, which a launcher takes as Profile\Default and its Fix
  switches plugins on from) is the order records\load-order.json gives, the
  one the server runs the Release on. Until #6298 every merge release packed
  the lists the last Ship from One recorded (10 Nov 2026, collection revision
  7), and with dev on revision 8 every dev launcher refused Play at Improved
  Eyes Skyrim.esp.

  It proves, on a scratch repository's records and the record's lists:
    - plugins.txt enables, in the record's order, each plugin the collection
      puts in Data and Thornswood's own, and nothing else (no game master,
      no storefront file), under the old header
    - a plugin the records add is enabled, one they take out is gone
    - loadorder.txt gets the added plugin right after the one before it in
      plugins.txt and keeps every other line
    - the old files' line endings and byte order mark are kept
    - a record that does not name one of our own plugins stops it
    - on this checkout's own records, the list is the record's order
      filtered the same way, Thornswood-Last.esp last
    - Build-SetupFiles.ps1 makes its profile\ lists this way
#>
$ErrorActionPreference = 'Stop'
$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$script:fails = 0; $script:passes = 0
function Yes([string]$what, [bool]$ok) {
  if ($ok) { Write-Host "PASS  $what"; $script:passes++ } else { Write-Host "FAIL  $what" -ForegroundColor Red; $script:fails++ }
}
. (Join-Path $Repo 'scripts/release/Reference-List.ps1')

$scratch = Join-Path ([IO.Path]::GetTempPath()) ('test-6298-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Path (Join-Path $scratch 'records') -Force | Out-Null
function Put([string]$rel, [string]$text) { [IO.File]::WriteAllText((Join-Path $scratch $rel), $text) }
function Lists([string]$dir, [string]$plugins, [string]$lo, [bool]$bom) {
  New-Item -ItemType Directory -Force -Path $dir | Out-Null
  $pre = if ($bom) { [byte[]](0xEF, 0xBB, 0xBF) } else { [byte[]]@() }
  [IO.File]::WriteAllBytes((Join-Path $dir 'plugins.txt'), [byte[]]($pre + [Text.Encoding]::UTF8.GetBytes($plugins)))
  [IO.File]::WriteAllBytes((Join-Path $dir 'loadorder.txt'), [byte[]]($pre + [Text.Encoding]::UTF8.GetBytes($lo)))
}
try {
  Put 'records/load-order.json' '{"version":1,"collection":"x","revision":8,"loadOrder":["Skyrim.esm","Update.esm","Dawnguard.esm","HearthFires.esm","Dragonborn.esm","_ResourcePack.esl","A.esm","B.esp","Thornswood-Content.esp","C.esp","Eyes.esp","Thornswood-Last.esp"]}'
  Put 'records/collection.json' '{"version":1,"plugins":[{"name":"A.esm"},{"name":"B.esp"},{"name":"C.esp"},{"name":"Eyes.esp"}]}'
  $p = Join-Path $scratch 'p1'
  Lists $p "# Automatically generated by Vortex`r`n*A.esm`r`n*B.esp`r`n*Gone.esp`r`n*Thornswood-Content.esp`r`n*C.esp`r`n*Thornswood-Last.esp`r`n" "# Automatically generated by Vortex`r`nSkyrim.esm`r`nUpdate.esm`r`nccX.esl`r`nA.esm`r`nB.esp`r`nThornswood-Content.esp`r`nC.esp`r`nThornswood-Last.esp`r`n" $false
  $added = @(Set-ThornswoodReferenceList $p $scratch)
  $pt = [IO.File]::ReadAllText((Join-Path $p 'plugins.txt'))
  $lt = [IO.File]::ReadAllText((Join-Path $p 'loadorder.txt'))
  Yes 'plugins.txt enables the collection''s plugins and ours in the record''s order, under the old header' ($pt -ceq "# Automatically generated by Vortex`r`n*A.esm`r`n*B.esp`r`n*Thornswood-Content.esp`r`n*C.esp`r`n*Eyes.esp`r`n*Thornswood-Last.esp`r`n")
  Yes '  no game master or storefront file, and the plugin the records took out is gone' (-not $pt.Contains('Skyrim.esm') -and -not $pt.Contains('_ResourcePack') -and -not $pt.Contains('Gone.esp'))
  Yes '  and it says which plugin it enabled that the old list did not' ($added.Count -eq 1 -and $added[0] -eq 'Eyes.esp')
  Yes 'loadorder.txt has the added plugin after the one before it, and every other line kept' ($lt -ceq "# Automatically generated by Vortex`r`nSkyrim.esm`r`nUpdate.esm`r`nccX.esl`r`nA.esm`r`nB.esp`r`nThornswood-Content.esp`r`nC.esp`r`nEyes.esp`r`nThornswood-Last.esp`r`n")

  $q = Join-Path $scratch 'p2'
  Lists $q "*A.esm`n*Thornswood-Last.esp`n" "A.esm`nThornswood-Last.esp`n" $true
  [void](Set-ThornswoodReferenceList $q $scratch)
  $qb = [IO.File]::ReadAllBytes((Join-Path $q 'plugins.txt'))
  $qt = [Text.Encoding]::UTF8.GetString($qb, 3, $qb.Length - 3)
  Yes 'a list with a byte order mark and LF keeps both' ($qb[0] -eq 0xEF -and $qb[1] -eq 0xBB -and $qb[2] -eq 0xBF -and -not $qt.Contains("`r") -and $qt.StartsWith('*A.esm'))

  Put 'records/load-order.json' '{"version":1,"loadOrder":["Skyrim.esm","A.esm","Thornswood-Content.esp"]}'
  $r = Join-Path $scratch 'p3'
  Lists $r "*A.esm`r`n" "A.esm`r`n" $false
  $threw = $false; try { [void](Set-ThornswoodReferenceList $r $scratch) } catch { $threw = $_.Exception.Message -match 'Thornswood-Last\.esp' }
  Yes 'a record that does not name Thornswood-Last.esp stops it, naming the plugin' $threw
} finally { Remove-Item -LiteralPath $scratch -Recurse -Force -EA SilentlyContinue }

# ---- this checkout's own records ------------------------------------------
$names = @(Get-ThornswoodReferencePlugins $Repo)
$order = @((Get-Content -Raw (Join-Path $Repo 'records/load-order.json') | ConvertFrom-Json).loadOrder)
$coll = @((Get-Content -Raw (Join-Path $Repo 'records/collection.json') | ConvertFrom-Json).plugins | ForEach-Object { $_.name })
$want = @($order | Where-Object { $coll -icontains $_ -or $_ -in 'Thornswood-Content.esp', 'Thornswood-Last.esp' })
Yes ("this checkout's list is records\load-order.json's order of the collection's plugins and ours ({0})" -f $names.Count) ((($names -join '|') -eq ($want -join '|')) -and $names.Count -gt 2 -and $names[-1] -eq 'Thornswood-Last.esp')
Yes '  without the five masters' (@($names | Where-Object { $_ -in 'Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'HearthFires.esm', 'Dragonborn.esm' }).Count -eq 0)

# ---- the release's package ------------------------------------------------
$bs = [IO.File]::ReadAllText((Join-Path $Repo 'scripts/release/Build-SetupFiles.ps1'))
$fetch = $bs.IndexOf('Get-FeedAssetFile $url $sha')
$make = $bs.IndexOf("Set-ThornswoodReferenceList (Join-Path `$files 'profile') `$RepoDir")
Yes 'Build-SetupFiles.ps1 makes its profile\ lists over from the records, after it fetches the record''s' ($fetch -gt 0 -and $make -gt $fetch -and $bs.Contains(". (Join-Path `$Here 'Reference-List.ps1')"))

Write-Host ''
Write-Host ("{0} passed, {1} failed" -f $script:passes, $script:fails)
if ($script:fails) { exit 1 }

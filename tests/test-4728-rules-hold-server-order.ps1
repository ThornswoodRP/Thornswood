<#
  test-4728-rules-hold-server-order.ps1

      pwsh -NoProfile -File .\tests\test-4728-rules-hold-server-order.ps1

  Issue #4728: Check-CollectionRules.ps1, run on the order the servers load,
  said NOT HELD and exited 1. CommonClothes.esp's only rule puts it after
  RaceMenuMorphsCBBE.esp, a plugin the collection installs switched off, so
  where that plugin is off nothing holds CommonClothes.esp in place and LOOT
  may move it. And the check counted a plugin a rule names that the list
  leaves off as a failure, though records\collection.json switches two off on
  purpose (enabled false: CBBE.esp and RaceMenuMorphsCBBE.esp).

  This builds the collection's rules out of records\collection.json, a Data
  folder of plugin headers out of the same record's facts (master, light and
  the masters each header names), and runs the real check as a child process
  on two lists:
    A. the order the servers load, game\data\last-plugin.json's loadOrder,
       with what the record installs that they do not load yet on the end and
       Thornswood-Last.esp last, as the live order ends;
    B. the collection's own list: the plugins the record switches on, in its
       order, as a clean install has them before the launcher switches on the
       rest.
  Both must be HELD, and the check must name each plugin it allows off, and
  why, rather than pass over it in silence.
#>
$ErrorActionPreference = 'Stop'
$Repo = Split-Path -Parent $PSScriptRoot
$Check = Join-Path (Join-Path (Join-Path $Repo 'scripts') 'mods') 'Check-CollectionRules.ps1'

$script:pass = 0
$script:fail = 0
function Yes([string]$what, [bool]$cond) {
    if ($cond) { $script:pass++; Write-Host "PASS  $what" }
    else { $script:fail++; Write-Host "FAIL  $what" }
}

$record = [IO.File]::ReadAllText((Join-Path (Join-Path $Repo 'records') 'collection.json')) | ConvertFrom-Json
$last = [IO.File]::ReadAllText((Join-Path (Join-Path (Join-Path $Repo 'game') 'data') 'last-plugin.json')) | ConvertFrom-Json
$off = @(@($record.plugins) | Where-Object { $_.enabled -eq $false } | ForEach-Object { [string]$_.name })
Yes ('records\collection.json switches plugins off on purpose (' + ($off -join ', ') + ')') ($off.Count -gt 0)

$root = Join-Path ([IO.Path]::GetTempPath()) ('thornswood-4728-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
$data = Join-Path $root 'Data'
$null = New-Item -ItemType Directory -Force -Path $data

# A plugin file with a TES4 header: flags 0x1 a master, 0x200 light, and a
# MAST field for each master its header names.
function Plugin([string]$name, [uint32]$flags, [string[]]$masters) {
    $fields = New-Object Collections.Generic.List[byte]
    foreach ($m in @($masters | Where-Object { $_ })) {
        $n = [Text.Encoding]::ASCII.GetBytes($m + [char]0)
        $fields.AddRange([Text.Encoding]::ASCII.GetBytes('MAST'))
        $fields.AddRange([BitConverter]::GetBytes([uint16]$n.Length))
        $fields.AddRange($n)
    }
    $b = New-Object byte[] (24 + $fields.Count)
    [Text.Encoding]::ASCII.GetBytes('TES4').CopyTo($b, 0)
    [BitConverter]::GetBytes([uint32]$fields.Count).CopyTo($b, 4)
    [BitConverter]::GetBytes($flags).CopyTo($b, 8)
    $fields.ToArray().CopyTo($b, 24)
    [IO.File]::WriteAllBytes((Join-Path $data $name), $b)
}
function PluginList([string]$path, [string[]]$names) {
    $text = (@('# Automatically generated by Vortex') + @($names | ForEach-Object { '*' + $_ })) -join "`r`n"
    [IO.File]::WriteAllText($path, $text + "`r`n", (New-Object Text.UTF8Encoding($false)))
}
function Run-Check([string]$list) {
    $shell = (Get-Process -Id $PID).Path
    $out = & $shell -NoProfile -File $Check -Collection (Join-Path $root 'collection.json') -List $list -Data $data -Root $root 2>&1 | ForEach-Object { "$_" }
    return [pscustomobject]@{ Code = $LASTEXITCODE; Text = ($out -join "`n") }
}

try {
    foreach ($m in @('Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'HearthFires.esm', 'Dragonborn.esm')) { Plugin $m 0x1 @() }
    Plugin '_ResourcePack.esl' 0x201 @()
    foreach ($p in @($record.plugins)) {
        $flags = [uint32]0
        if ($p.master) { $flags = $flags -bor 0x1 }
        if ($p.light) { $flags = $flags -bor 0x200 }
        Plugin ([string]$p.name) $flags ([string[]]@($p.masters))
    }
    # Built on each machine from its recipe, a full plugin, always last.
    Plugin 'Thornswood-Last.esp' 0 @('Skyrim.esm')

    # The collection's rules as Vortex writes them: lower case.
    $rules = @(@($record.plugins) | Where-Object { @($_.after).Count } | ForEach-Object {
            [ordered]@{ name = ([string]$_.name).ToLowerInvariant(); after = @(@($_.after) | ForEach-Object { ([string]$_).ToLowerInvariant() }) } })
    $doc = [ordered]@{ info = [ordered]@{ name = 'Thornswood' }; mods = @(); pluginRules = [ordered]@{ plugins = $rules; groups = @() } }
    [IO.File]::WriteAllText((Join-Path $root 'collection.json'), ($doc | ConvertTo-Json -Depth 8), (New-Object Text.UTF8Encoding($false)))

    # A. The order the servers load, with what the record installs that they
    # do not load yet on the end, as Deploy-Gamemode.ps1 -Vortex leaves it
    # before the check runs (docs\COLLECTION-REBUILD-7ESSXF.md, steps 2 and 3).
    $servers = @(@($last.loadOrder) | ForEach-Object { [string]$_ })
    $pending = @(@($record.plugins) | Where-Object { $_.enabled -ne $false -and $servers -notcontains [string]$_.name } | ForEach-Object { [string]$_.name })
    $servers = $servers + $pending + @('Thornswood-Last.esp')
    PluginList (Join-Path $root 'servers.txt') $servers
    $a = Run-Check (Join-Path $root 'servers.txt')
    Yes "A. the collection's rules hold the order the servers load (exit $($a.Code))" ($a.Code -eq 0 -and $a.Text -match 'HELD\.')
    if ($a.Code -ne 0) { foreach ($l in ($a.Text -split "`n" | Where-Object { $_ -match '^\s+(NO|  )' -or $_ -match '^\s{10}' })) { Write-Host "      $l" } }

    # B. The collection's own list, which leaves the off plugins out.
    $own = @('Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'HearthFires.esm', 'Dragonborn.esm') +
        @(@($record.plugins) | Where-Object { $_.enabled -ne $false } | ForEach-Object { [string]$_.name })
    PluginList (Join-Path $root 'own.txt') $own
    $b = Run-Check (Join-Path $root 'own.txt')
    Yes "B. the collection's rules hold its own list, with the plugins it switches off left out (exit $($b.Code))" ($b.Code -eq 0 -and $b.Text -match 'HELD\.')
    if ($b.Code -ne 0) { foreach ($l in ($b.Text -split "`n" | Where-Object { $_ -match '^\s{10}' })) { Write-Host "      $l" } }
    foreach ($n in $off) {
        $said = @($b.Text -split "`n" | Where-Object { $_ -match [regex]::Escape($n) -and $_ -match 'allowed off' -and $_ -match 'records.collection\.json' })
        Yes "B. the check names $n as allowed off, and where that is written" ($said.Count -ge 1)
    }
} finally {
    Remove-Item -LiteralPath $root -Recurse -Force -ErrorAction SilentlyContinue
}

Write-Host ''
Write-Host ("{0} passed, {1} failed" -f $script:pass, $script:fail)
if ($script:fail) { exit 1 }
exit 0

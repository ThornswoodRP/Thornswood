<#
  test-4687-setup-plugin-list.ps1

      pwsh -NoProfile -File .\tests\test-4687-setup-plugin-list.ps1

  An installer is never built without its plugin list (#4687).

  The install a launcher runs on its first start reads the reference load
  order, profile\plugins.txt and loadorder.txt, from its Velopack package
  (launcher\app\InstallSteps.cs). merge-release.yml builds those files with
  Build-SetupFiles.ps1 before it builds or signs the launcher, packs the
  package, signs the catalog or publishes the Release, and stops the job when
  it fails. Since #4824 there is one package per channel for every install,
  so no build may go without the list: there is no collection-only build to
  let through.

  This runs the real Build-SetupFiles.ps1 against a stand-in site (-SiteDir)
  and a staged record, and holds:
    1. a release that recorded no plugins.txt stops it, naming the list, with
       no list packed and no setup-files list written
    2. the same for a release that recorded no loadorder.txt
    3. a release that recorded both gets past that step: both lists are
       packed into profile\
    4. in merge-release.yml, Build-SetupFiles.ps1 runs before the launcher is
       built and signed and before the catalog is signed, and a failure ends
       the job

  Nothing connects anywhere, and everything it writes is in its own temp folder.
#>
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Here = $PSScriptRoot
if (-not $Here) { $Here = Split-Path -Parent $MyInvocation.MyCommand.Definition }
$repo = Split-Path -Parent $Here
$rel = Join-Path $repo 'scripts\release'

$script:pass = 0; $script:fail = 0
function Yes([string]$what, [bool]$cond) {
    if ($cond) { $script:pass++; Write-Host "PASS  $what" }
    else { $script:fail++; Write-Host "FAIL  $what" -ForegroundColor Red }
}
function Put([string]$path, $content) {
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    if ($content -is [byte[]]) { [IO.File]::WriteAllBytes($path, $content) }
    else { [IO.File]::WriteAllText($path, [string]$content, (New-Object Text.UTF8Encoding($false))) }
}
function ShaBytes([byte[]]$b) {
    $h = [Security.Cryptography.SHA256]::Create()
    try { return -join ($h.ComputeHash($b) | ForEach-Object { $_.ToString('x2') }) } finally { $h.Dispose() }
}
function Utf8([string]$s) { return [Text.Encoding]::UTF8.GetBytes($s) }

. (Join-Path $rel 'Release-Baseline.ps1')   # Write-BaselineFile: the record as a release writes it

$Scratch = Join-Path ([IO.Path]::GetTempPath()) ('ts-4687-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Force -Path $Scratch | Out-Null
try {
    $site = Join-Path $Scratch 'site'
    $assets = Join-Path $site 'feed-dev\assets'
    function Asset([byte[]]$b) { $s = ShaBytes $b; Put (Join-Path $assets $s) $b; return $s }
    $plugins = Utf8 "# Automatically generated by Vortex`r`n*Thornswood-Content.esp`r`n*Thornswood-Last.esp`r`n"
    $loadorder = Utf8 "# Automatically generated by Vortex`r`nSkyrim.esm`r`nThornswood-Content.esp`r`nThornswood-Last.esp`r`n"
    $sPlugins = Asset $plugins; $sLoadorder = Asset $loadorder
    $gameRoot = Join-Path $Scratch 'game-root'
    New-Item -ItemType Directory -Force -Path (Join-Path $gameRoot 'Game\Data') | Out-Null
    $out = Join-Path $Scratch 'setup-dev'

    # A release's record holding the lists named in $lists, staged where
    # New-FeedRoot.ps1 leaves it and named by the dev feed as its last release.
    function Set-Release([string[]]$lists) {
        $map = @{ ':record:files' = '1' }
        if ($lists -contains 'plugins.txt') { $map[':golden:plugins.txt'] = ('{0}:{1}' -f $plugins.Length, $sPlugins) }
        if ($lists -contains 'loadorder.txt') { $map[':golden:loadorder.txt'] = ('{0}:{1}' -f $loadorder.Length, $sLoadorder) }
        $staged = Join-Path $gameRoot 'record\record.json'
        $sha = Write-BaselineFile $map $staged
        Put (Join-Path $assets $sha) ([IO.File]::ReadAllBytes($staged))
        $feed = [ordered]@{
            launcherVersion = '1.3.80'; packs = @(); serverAddress = '192.0.2.7'; serverPort = 7788; siteUrl = 'https://thornswood.net'
            baseline = [ordered]@{ id = '20261116-120000-dev'; sha256 = $sha; url = "https://thornswood.net/feed-dev/assets/$sha"; entries = $map.Count }
        }
        Put (Join-Path $site 'feed-dev\version\00000001.json') (([pscustomobject]$feed) | ConvertTo-Json -Depth 5)
    }
    $Shell = (Get-Process -Id $PID).Path
    function Build {
        $oldE = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
        try { $o = (& $Shell -NoProfile -NonInteractive -File (Join-Path $rel 'Build-SetupFiles.ps1') -Out $out -GameRoot $gameRoot -Channel dev -Commit ('a' * 40) -SiteDir $site 2>&1 | Out-String); $code = $LASTEXITCODE }
        finally { $ErrorActionPreference = $oldE }
        # Squashed: the refusal is an error record, which PowerShell wraps at
        # the console's width on a runner.
        return [pscustomobject]@{ Code = $code; Out = $o; Squashed = ($o -replace '[\s|]', '') }
    }
    $profileDir = Join-Path $out 'files\profile'
    $listFile = Join-Path $out 'setup-files.dev.json'

    # ---- 1. no plugins.txt -------------------------------------------------------------
    Write-Host ''; Write-Host 'a release that recorded no plugins.txt'
    Set-Release @('loadorder.txt')
    $r = Build
    Yes ("Build-SetupFiles stops (exit {0})" -f $r.Code) ($r.Code -ne 0)
    Yes '  saying the release recorded no plugins.txt, so the install would carry no reference load order' ($r.Squashed -match 'recordednoplugins\.txt' -and $r.Squashed -match 'noreferenceloadorder')
    Yes '  with no plugin list packed' (-not (Test-Path -LiteralPath (Join-Path $profileDir 'plugins.txt')))
    Yes '  and no setup-files list for a package to be built from' (-not (Test-Path -LiteralPath $listFile))
    if ($r.Code -eq 0 -or $r.Squashed -notmatch 'recordednoplugins\.txt') { Write-Host $r.Out -ForegroundColor DarkGray }

    # ---- 2. no loadorder.txt -----------------------------------------------------------
    Write-Host ''; Write-Host 'a release that recorded no loadorder.txt'
    Set-Release @('plugins.txt')
    $r = Build
    Yes ("Build-SetupFiles stops (exit {0})" -f $r.Code) ($r.Code -ne 0)
    Yes '  saying the release recorded no loadorder.txt' ($r.Squashed -match 'recordednoloadorder\.txt')
    Yes '  and no setup-files list is written' (-not (Test-Path -LiteralPath $listFile))

    # ---- 3. both lists -----------------------------------------------------------------
    Write-Host ''; Write-Host 'a release that recorded both lists'
    Set-Release @('plugins.txt', 'loadorder.txt')
    $r = Build
    Yes '  it is not stopped for a missing list' ($r.Squashed -notmatch 'recordedno(plugins|loadorder)\.txt')
    $pGot = Join-Path $profileDir 'plugins.txt'; $lGot = Join-Path $profileDir 'loadorder.txt'
    Yes '  and packs both lists into profile\, going on past that step' ((Test-Path -LiteralPath $pGot) -and (Test-Path -LiteralPath $lGot) -and $r.Out -match 'profile\\: plugins\.txt and loadorder\.txt of release 20261116-120000-dev')
    if (-not (Test-Path -LiteralPath $pGot)) { Write-Host $r.Out -ForegroundColor DarkGray }

    # ---- 4. where it runs in the release --------------------------------------------
    Write-Host ''; Write-Host 'merge-release.yml'
    $wf = [IO.File]::ReadAllText((Join-Path $repo '.github\workflows\merge-release.yml'))
    $iSetup = $wf.IndexOf('./scripts/release/Build-SetupFiles.ps1 -Out')
    $iLauncher = $wf.IndexOf('- name: The launcher, built and signed')
    $iPack = $wf.IndexOf('- name: Pack the launcher and the game files with Velopack')
    $iSign = $wf.IndexOf('- name: Sign the catalog')
    $iPublish = $wf.IndexOf('- name: Publish the Release')
    Yes 'Build-SetupFiles runs before the launcher is built and signed, the package is packed, the catalog is signed and the Release is published' (
        $iSetup -gt 0 -and $iSetup -lt $iLauncher -and $iLauncher -lt $iPack -and $iPack -lt $iSign -and $iSign -lt $iPublish)
    Yes '  and its failure ends the job' ($wf.Contains('if ($LASTEXITCODE -ne 0) { Write-Host "::error::Build-SetupFiles.ps1 -Channel $ch failed; the lines above say why"; exit 1 }'))
}
finally {
    Remove-Item -LiteralPath $Scratch -Recurse -Force -ErrorAction SilentlyContinue
}
Write-Host ''
Write-Host ("{0} passed, {1} failed" -f $script:pass, $script:fail)
if ($script:fail) { exit 1 }
exit 0
